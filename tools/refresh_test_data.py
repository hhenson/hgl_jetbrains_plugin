#!/usr/bin/env python3
"""Extract complete HGL modules and applications from the pinned spec and copy core sources."""
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src/test/testData/parser"
documents = sorted((ROOT / "spec/hgl_spec").rglob("*.md"))
core_sources = sorted((ROOT / "spec/hgl_core").rglob("*.hgl"))
if not documents or not core_sources:
    raise SystemExit("Initialize the pinned sources: git submodule update --init --recursive")
for name in ("spec", "core"):
    shutil.rmtree(DEST / name, ignore_errors=True)
    (DEST / name).mkdir()
# Include declaration examples that precede executable core implementations.
mapping = ROOT / "spec/hgl_core/spec/mapping.md"
declaration = re.compile(r"^(?:(?:export|abstract|impl|native|const) )*(?:fn|operator|struct|enum|type) ")
for document in [*documents, mapping]:
    for number, block in enumerate(re.findall(r"```hgl\n(.*?)```", document.read_text(), re.S)):
        first_line = next((line for line in block.splitlines() if line.strip() and not line.startswith("#")), "")
        complete = re.search(r"^(?:module|application) ", block, re.M)
        fragment = document.parent.name == "language" and declaration.match(first_line)
        if complete or fragment or document == mapping:
            if document == mapping:
                destination = DEST / "core" / f"spec_{document.stem}-{number}.hgl"
            else:
                destination = DEST / "spec" / f"{document.stem}-{number}.hgl"
            if destination.exists():
                raise SystemExit(f"Duplicate fixture name: {destination.name}")
            destination.write_text(block)
for source in core_sources:
    name = "_".join(source.relative_to(ROOT / "spec/hgl_core").parts)
    (DEST / "core" / name).write_text(source.read_text())
lines = ["# Fixture sources", "", "Generated by tools/refresh_test_data.py.", ""]
for name in ("hgl_spec", "hgl_core"):
    revision = subprocess.check_output(["git", "-C", str(ROOT / "spec" / name), "rev-parse", "HEAD"], text=True).strip()
    lines.append(f"- {name} at `{revision}`")
(DEST / "SOURCES.md").write_text("\n".join(lines) + "\n")
